# range(0,4) -> [0, 1, 2, 3]
for i in range(0, 4):
    print(i)

# mudando a passada (pula de 2 em 2)

for i in range(0, 4, 2):
    print(i)

# contar para trás (pula de 2 em 2)
for i in range(4, -1, -2):
    print(i)

# 'range' em texto 
macacos = ['Mico leão dourado', 'Macaco Aranha', 'Macaco prego']

for macaco in macacos:
    print(macaco)

